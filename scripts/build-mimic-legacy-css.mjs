// One-shot script: copy original akhbaralyawm stylesheets into the repo and
// prefix every selector with `.mimic-root` so they only apply to v2 routes.
//
// Inputs:  public/اليوم_files/{bootstrap.rtl.min.css, style.css, responsive.css, rtl.css}
// Output:  src/components/mimic/legacy/<name>.scoped.css   (committed to repo)
// Plus:    src/components/mimic/legacy/index.css           (single import)
//
// Run:     node scripts/build-mimic-legacy-css.mjs

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import postcss from "postcss";
import prefixer from "postcss-prefix-selector";

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, "public", "اليوم_files");
const OUT_DIR = path.join(ROOT, "src", "components", "mimic", "legacy");
const SCOPE = ".mimic-root";

// Order matters: bootstrap -> theme -> responsive -> rtl
const FILES = [
  "bootstrap.rtl.min.css",
  "icofont.min.css",
  "style.css",
  "responsive.css",
  "rtl.css",
];

// Selectors that target the page root. We rewrite these so the scoped output
// keeps applying to body/html-level rules without leaking outside .mimic-root.
const ROOT_SELECTORS = new Set(["html", "body", ":root", "*", "*::before", "*::after", "*:before", "*:after"]);

function transformSelector(selector) {
  const trimmed = selector.trim();
  if (!trimmed) return selector;
  if (ROOT_SELECTORS.has(trimmed)) return SCOPE;
  // Skip @keyframes inner selectors (from/to/percent)
  if (/^(\d+%|from|to)$/i.test(trimmed)) return selector;
  return `${SCOPE} ${trimmed}`;
}

await mkdir(OUT_DIR, { recursive: true });

const imports = [];

// Collect all `@import url(...)` statements separately so we can hoist them
// above the prefixed selectors (CSS spec requires @imports to come first).
const HOISTED_IMPORTS = new Set();

const URL_REWRITE_BASE = "https://www.akhbaralyawm.com/";

function rewriteUrl(originalUrl) {
  const trimmed = originalUrl.trim().replace(/^['"]|['"]$/g, "");
  // Leave data:, blob:, http(s):, // and # alone
  if (/^(data:|blob:|https?:|\/\/|#)/i.test(trimmed)) return null;
  // Handle ../fonts/ pattern: icofont lives at /assets/fonts/ relative to /assets/css/
  if (trimmed.startsWith("../fonts/")) {
    return `${URL_REWRITE_BASE}assets/fonts/${trimmed.slice("../fonts/".length)}`;
  }
  // Strip leading ./ and ../ chains
  const clean = trimmed.replace(/^(\.{1,2}\/)+/g, "");
  return `${URL_REWRITE_BASE}${clean}`;
}

const rewriteUrls = () => ({
  postcssPlugin: "rewrite-relative-urls",
  Declaration(decl) {
    if (!decl.value.includes("url(")) return;
    decl.value = decl.value.replace(/url\(\s*([^)]+?)\s*\)/g, (match, raw) => {
      const replaced = rewriteUrl(raw);
      return replaced ? `url("${replaced}")` : match;
    });
  },
  AtRule: {
    import(rule) {
      HOISTED_IMPORTS.add(`@import ${rule.params};`);
      rule.remove();
    },
  },
});
rewriteUrls.postcss = true;

for (const file of FILES) {
  const inPath = path.join(SRC_DIR, file);
  const css = await readFile(inPath, "utf8");

  const result = await postcss([
    rewriteUrls(),
    prefixer({
      prefix: SCOPE,
      transform: (_prefix, selector) => transformSelector(selector),
    }),
  ]).process(css, { from: inPath, to: undefined });

  const outName = file.replace(/\.css$/, ".scoped.css");
  const outPath = path.join(OUT_DIR, outName);
  await writeFile(outPath, result.css, "utf8");
  imports.push(`@import "./${outName}";`);
  // eslint-disable-next-line no-console
  console.log(`scoped ${file} -> ${outName} (${(result.css.length / 1024).toFixed(1)} KB)`);
}

const indexHeader =
  "/* AUTO-GENERATED by scripts/build-mimic-legacy-css.mjs. Do not edit. */\n" +
  '/* All rules are scoped under `.mimic-root` so they only apply to v2. */\n\n';

const hoistedBlock = Array.from(HOISTED_IMPORTS).join("\n");

await writeFile(
  path.join(OUT_DIR, "index.css"),
  indexHeader + (hoistedBlock ? hoistedBlock + "\n\n" : "") + imports.join("\n") + "\n",
  "utf8",
);
console.log(`wrote ${path.join(OUT_DIR, "index.css")}`);
